#!/usr/bin/env bash
# make-lock.sh TYPE SOURCE OUT - write the image lock file for TYPE (client|router) from a pins list (idea#322).
# SOURCE: two (or more) tab-separated columns: package, version[, arch]. Comment lines (#) are dropped.
# OUT gets a header (format, type, source name + sha256, entry count) and the sorted package<TAB>version list.
# Fails (exit 1) on an empty list, a malformed line or a duplicate package; exit 2 on usage error.
set -euo pipefail
[ $# = 3 ] || { echo "usage: make-lock.sh client|router SOURCE OUT" >&2; exit 2; }
TYPE=$1; SRC=$2; OUT=$3
case "$TYPE" in client|router) ;; *) echo "type must be client or router" >&2; exit 2;; esac
[ -r "$SRC" ] || { echo "cannot read $SRC" >&2; exit 2; }
body=$(grep -v '^#' "$SRC" | grep -v '^[[:space:]]*$' | awk -F'\t' 'NF<2||$1==""||$2==""{print "bad line " NR ": " $0 > "/dev/stderr"; bad=1} {print $1"\t"$2} END{exit bad}' | LC_ALL=C sort) \
  || { echo "malformed pins in $SRC" >&2; exit 1; }
[ -n "$body" ] || { echo "no pins in $SRC" >&2; exit 1; }
dup=$(cut -f1 <<<"$body" | uniq -d | head -5 | xargs)
[ -z "$dup" ] || { echo "duplicate packages in $SRC: $dup" >&2; exit 1; }
n=$(wc -l <<<"$body"); sha=$(sha256sum "$SRC" | cut -d' ' -f1)
{ echo "# idea-lock v1 type=$TYPE source=$(basename "$SRC") source_sha256=$sha entries=$n"
  echo "# Generated by tools/repro/make-lock.sh - do not edit by hand. The build installs exactly these versions."
  printf '%s\n' "$body"; } > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"; echo "lock: $OUT ($TYPE, $n entries)"
